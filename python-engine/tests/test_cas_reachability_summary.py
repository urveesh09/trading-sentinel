def test_update_summary_is_idempotent(tmp_path):
    """Running ``update_summary`` twice with the same report
    produces byte-identical files except for the
    ``generated_at_utc`` timestamp.
    """
    report = cas_reachability_report(captures_dir=tmp_path)
    summary_path = tmp_path / "SUMMARY.md"
    update_summary(report, summary_path=summary_path)
    first = summary_path.read_text(encoding="utf-8")
    update_summary(report, summary_path=summary_path)
    second = summary_path.read_text(encoding="utf-8")
    # Strip the timestamp line for comparison (we can't make it
    # deterministic without faking the clock; rule out drift
    # everywhere else).
    def _strip_ts(s: str) -> str:
        return "\n".join(
            line for line in s.splitlines()
            if not line.startswith("**Generated at")
        )
    assert _strip_ts(first) == _strip_ts(second)


