def _missing_section(text: str) -> str:
    """Return the section of a SUMMARY.md that lists missing
    branches. Used to assert that captured branches do NOT
    appear in the missing list.
    """
    lines = text.splitlines()
    start = None
    end = len(lines)
    for i, line in enumerate(lines):
        if "missing" in line.lower() and ("branch" in line.lower() or "phase" in line.lower()):
            start = i + 1
            break
    if start is None:
        return ""
    for i in range(start, len(lines)):
        if lines[i].startswith("## "):
            end = i
            break
    return "\n".join(lines[start:end])
